"use client";

import type { ReactNode } from "react";
import { useTheme } from "./ThemeProvider";
import styles from "./QuizThemeSurface.module.css";

const artwork = {
  itbegan: {
    eyebrow: "A NEW DAY // A FRESH START",
    title: "IT BEGAN.",
    caption: "one question at a time. you've got this.",
  },
  itsover: {
    eyebrow: "SIGNAL LOST // ACADEMIC WINTER",
    title: "IT'S OVER.",
    caption: "hope.exe is not responding",
  },
  larp: {
    eyebrow: "CLUTCH MODE // ULTRA LARP AURA +999999",
    title: "NO LIMIT.",
    caption: "the exam is temporary. the ultra larp lore is forever.",
  },
};

export function QuizThemeSurface({ children, className }: {
  children: ReactNode;
  className: string;
}) {
  const { theme } = useTheme();
  const memeTheme = theme === "larp" || theme === "itsover" || theme === "itbegan" ? theme : null;
  const copy = memeTheme ? artwork[memeTheme] : null;

  return (
    <div className={`${className} ${memeTheme ? `${styles.pane} ${styles[memeTheme]}` : ""}`}>
      {copy && (
        <div
          className={styles.atmosphere}
          aria-hidden="true"
          // Never become a flex row, even while the stylesheet is loading.
          style={{ position: "absolute", inset: 0, pointerEvents: "none", overflow: "hidden" }}
        >
          <div className={styles.signature}>
            {/* Decorative copy is generated by CSS. Without that CSS it stays
                invisible instead of leaking unstyled text into the quiz. */}
            <span className={styles.eyebrow} data-text={copy.eyebrow} />
            <strong className={styles.title} data-text={copy.title} />
            <span className={styles.caption} data-text={copy.caption} />
          </div>
        </div>
      )}
      {children}
    </div>
  );
}
